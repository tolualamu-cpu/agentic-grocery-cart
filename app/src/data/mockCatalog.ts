function product(
  id: string,
  canonicalName: string,
  category: string,
  subcategory: string,
  tags: string[],
  aliases: string[],
  semanticTags: string[],
  dietaryTags: string[] = [],
): Product {
  return { id, canonicalName, category, subcategory, tags, aliases, semanticTags, dietaryTags, image: productImage(id, canonicalName) };
}

function enrichCoreProduct(productItem: ProductInput): Product {
  const enrichment = coreProductTaxonomy[productItem.id];

  if (!enrichment) {
    return {
      ...productItem,
      image: productItem.image ?? productImage(productItem.id, productItem.canonicalName),
    };
  }

  return {
    ...productItem,
    ...enrichment,
    aliases: uniqueStrings([...(productItem.aliases ?? []), ...(enrichment.aliases ?? [])]),
    tags: uniqueStrings([...productItem.tags, ...(enrichment.tags ?? [])]),
    semanticTags: uniqueStrings([...(productItem.semanticTags ?? []), ...(enrichment.semanticTags ?? [])]),
    dietaryTags: uniqueStrings([...(productItem.dietaryTags ?? []), ...(enrichment.dietaryTags ?? [])]),
    image: productItem.image ?? enrichment.image ?? productImage(productItem.id, productItem.canonicalName),
  };
}

